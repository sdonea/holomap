export const PORTS: Port[] = [];
const byCode = new Map<string, Port>(), byName = new Map<string, Port>();
for (const line of TABLE.trim().split("\n")) {
  const [code, name, lat, lon, alt] = line.split("|");
  const p = { code, name, lat: Number(lat), lon: Number(lon) };
  PORTS.push(p);
  byCode.set(code, p);
  for (const n of [name, ...(alt ? alt.split(",") : [])]) if (!byName.has(n)) byName.set(n, p);
}

// Best port for an AIS destination string, or null when there's no confident match.
export function matchDestination(raw?: string): Port | null {
  if (!raw) return null;
  // "A>B" / "A=>B" / "A - B" chains: the ship is headed to the last one
  const last = raw.toUpperCase().split(/>|=>|->|\s-\s/).pop()!;
  const s = last.replace(/[^A-Z]+/g, " ").trim();
  if (!s) return null;
  const compact = s.replace(/ /g, "");
  if (compact.length === 5 && byCode.has(compact)) return byCode.get(compact)!; // "NLRTM", "NL RTM"
  // longest run of whole words that names a port: "NORFOLK VA", "CORPUS CHRISTI TX", "NJ NYC FERRY SVC"
  const words = s.split(" ");
  for (let n = words.length; n >= 1; n--)
    for (let i = 0; i + n <= words.length; i++) {
      const p = byName.get(words.slice(i, i + n).join(" "));
      if (p) return p;
    }
  return null;
}

// AIS ETA ("SEP 29 22:00 UTC") has no year: take the occurrence nearest to now.
export function parseAisEta(eta?: string, now = Date.now()): number | null {
  const m = eta?.match(/^([A-Z]{3}) (\d\d) (\d\d):(\d\d)/);
  if (!m) return null;
  const mo = "JAN FEB MAR APR MAY JUN JUL AUG SEP OCT NOV DEC".split(" ").indexOf(m[1]);
  if (mo < 0) return null;
  const y = new Date(now).getUTCFullYear();
  const at = (yr: number) => Date.UTC(yr, mo, +m[2], +m[3], +m[4]);
  return [y - 1, y, y + 1].map(at).reduce((a, b) => (Math.abs(b - now) < Math.abs(a - now) ? b : a));
}
